package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.GeneratorError
import com.qeetgroup.qeetrix.gen.KotlinNames
import com.qeetgroup.qeetrix.gen.icons.IconDrawing
import com.qeetgroup.qeetrix.gen.icons.PathCommand
import com.qeetgroup.qeetrix.gen.kotlinString
import com.qeetgroup.qeetrix.gen.numberText

/** One icon: its manifest entry and its drawings by `shape-variant`. */
data class IconSource(
    val name: String,
    val componentName: String,
    val directionality: String,
    val shapes: List<String>,
    val variants: List<String>,
    val drawings: Map<String, IconDrawing>,
)

/**
 * Writes the icons as Kotlin. Each drawing is one compact string ([encode]) that `QeetrixIconName` decodes the first
 * time the drawing is drawn, so thousands of icons cost little source, compile time or size.
 *
 * - The **core** icons (the pins) become `QeetrixIconCatalogue`, which `QeetrixIconName`'s companion inherits:
 *   `QeetrixIconName.Send`.
 * - With the extended catalogue, **every other** icon becomes an extension property on `QeetrixIconName.Companion` in
 *   the `qeetrix-icons-extended` module, one file — one class — per icon, so R8 keeps only the icons an app names.
 */
class IconEmitter(
    private val core: List<IconSource>,
    private val extended: List<IconSource>,
    private val provenance: Provenance,
) {
    fun files(): Map<String, String> {
        for (icon in core + extended) validate(icon)
        KotlinNames.requireUnique((core + extended).map { kotlinName(it) to it.name }, "icons")
        // One file per icon: names must stay apart on case-insensitive file systems too.
        KotlinNames.requireUnique((core + extended).map { kotlinName(it).lowercase() to it.name }, "icon files")
        val out = linkedMapOf("$GENERATED_DIR/QeetrixIconCatalogue.kt" to coreFile())
        if (extended.isNotEmpty()) {
            for (icon in extended) out["$EXTENDED_DIR/${kotlinName(icon)}.kt"] = extendedFile(icon)
            out["$EXTENDED_DIR/ExtendedCatalogue.kt"] = extendedCatalogueFile()
        }
        return out
    }

    private fun validate(icon: IconSource) {
        if (!icon.shapes.all { it in SHAPES } || !icon.variants.all { it in VARIANTS }) {
            throw GeneratorError(
                "${icon.name}: shapes ${icon.shapes} / variants ${icon.variants} include one QeetrixIconShape/Variant does not have.",
            )
        }
        if ("round-outline" !in icon.drawings) throw GeneratorError("${icon.name}: no round outline, which every icon falls back to.")
        if (icon.directionality !in setOf("preserve", "mirror")) {
            throw GeneratorError("${icon.name}: unknown directionality ${icon.directionality}.")
        }
    }

    private fun header(): String =
        "// GENERATED by qeetrix-gen from ${provenance.icons.packageName} ${provenance.icons.version} " +
            "(git ${provenance.icons.gitHead.take(7)}) — do not edit.\n"

    private fun coreFile(): String {
        val out = StringBuilder(header())
        out.appendLine("// Pin an icon in Upstream/manifest.json, run Scripts/sync-tokens, then Scripts/generate-tokens.")
        out.appendLine()
        out.appendLine("@file:OptIn(QeetrixGeneratedIconApi::class)")
        out.appendLine()
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixGeneratedIconApi")
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixIconName")
        out.appendLine()
        out.appendLine("/**")
        out.appendLine(" * The core icons: the ones Qeetrix's components and the sample draw, pinned in `Upstream/manifest.json`.")
        out.appendLine(" * [QeetrixIconName]'s companion inherits them, so they read `QeetrixIconName.Send`. Every other")
        out.appendLine(" * `@qeetrix/icons` icon is in the optional `com.qeetgroup:qeetrix-icons-extended` module.")
        out.appendLine(" */")
        out.appendLine("public abstract class QeetrixIconCatalogue internal constructor() {")
        for (icon in core) {
            out.appendLine("    /** ${doc(icon)} */")
            out.appendLine("    public val ${kotlinName(icon)}: QeetrixIconName =")
            out.appendLine("        ${constructor(icon, "        ")}")
            out.appendLine()
        }
        out.appendLine("    /** Every core icon, in name order. */")
        out.appendLine("    public val catalogue: List<QeetrixIconName> by lazy {")
        out.appendLine("        listOf(")
        for (icon in core) out.appendLine("            ${kotlinName(icon)},")
        out.appendLine("        )")
        out.appendLine("    }")
        out.appendLine("}")
        return out.toString()
    }

    private fun extendedFile(icon: IconSource): String {
        val name = kotlinName(icon)
        val out = StringBuilder(header())
        out.appendLine()
        out.appendLine("@file:OptIn(QeetrixGeneratedIconApi::class)")
        out.appendLine()
        out.appendLine("package $EXTENDED_PACKAGE")
        out.appendLine()
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixGeneratedIconApi")
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixIconName")
        out.appendLine()
        out.appendLine("/** ${doc(icon)} */")
        out.appendLine("public val QeetrixIconName.Companion.$name: QeetrixIconName")
        out.appendLine("    get() = icon")
        out.appendLine()
        out.appendLine("private val icon: QeetrixIconName =")
        out.appendLine("    ${constructor(icon, "    ")}")
        return out.toString()
    }

    private fun extendedCatalogueFile(): String {
        val out = StringBuilder(header())
        out.appendLine()
        out.appendLine("package $EXTENDED_PACKAGE")
        out.appendLine()
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixIconName")
        out.appendLine()
        out.appendLine("/**")
        out.appendLine(" * Every icon this module adds (${extended.size}), in name order — for an icon picker or a gallery. Naming it")
        out.appendLine(" * keeps every one of their drawings in the app, so an app that draws fixed icons names them instead.")
        out.appendLine(" */")
        out.appendLine("public val QeetrixIconName.Companion.extendedCatalogue: List<QeetrixIconName>")
        out.appendLine("    get() = all")
        out.appendLine()
        out.appendLine("private val all: List<QeetrixIconName> by lazy {")
        out.appendLine("    listOf(")
        for (icon in extended) out.appendLine("        QeetrixIconName.${kotlinName(icon)},")
        out.appendLine("    )")
        out.appendLine("}")
        return out.toString()
    }

    private fun doc(icon: IconSource): String =
        "`${icon.name}` — `${icon.componentName}` in @qeetrix/icons. Drawings: ${
            SHAPES.flatMap { s -> VARIANTS.map { "$s-$it" } }.filter { it in icon.drawings }.joinToString(", ")
        }" + if (icon.directionality == "mirror") "; mirrors in right to left." else "."

    private fun constructor(
        icon: IconSource,
        indent: String,
    ): String {
        fun drawing(key: String) = icon.drawings[key]?.let { kotlinString(encode(it)) } ?: "null"
        return buildString {
            append("QeetrixIconName(\n")
            append("$indent    value = ${kotlinString(icon.name)},\n")
            append("$indent    mirrorsInRightToLeft = ${icon.directionality == "mirror"},\n")
            append("$indent    roundOutline = ${drawing("round-outline")},\n")
            append("$indent    roundFilled = ${drawing("round-filled")},\n")
            append("$indent    sharpOutline = ${drawing("sharp-outline")},\n")
            append("$indent    sharpFilled = ${drawing("sharp-filled")},\n")
            append("$indent)")
        }
    }

    private fun kotlinName(icon: IconSource) = KotlinNames.pascal(listOf(icon.name), icon.name)

    companion object {
        const val PACKAGE = "com.qeetgroup.qeetrix.icons.generated"
        const val GENERATED_DIR = "qeetrix/src/main/kotlin/com/qeetgroup/qeetrix/icons/generated"
        const val EXTENDED_PACKAGE = "com.qeetgroup.qeetrix.icons.extended"
        const val EXTENDED_DIR = "qeetrix-icons-extended/src/main/kotlin/com/qeetgroup/qeetrix/icons/extended"
        private val SHAPES = listOf("round", "sharp")
        private val VARIANTS = listOf("outline", "filled")

        /**
         * A drawing as one string, decoded by `QeetrixIconName` (qeetrix/…/internal/QeetrixIconCodec.kt):
         * the miter limit, then each element after a `|` — four flags (fill `-`/`n`onzero/`e`ven-odd, stroke `-`/`s`,
         * cap `b`utt/`r`ound/`s`quare, join `m`iter/`r`ound/`b`evel) and its absolute commands, `M x y`, `L x y`,
         * `Q x1 y1 x y`, `C x1 y1 x2 y2 x y` and `Z`, numbers at six decimals as the rest of the generator writes them.
         */
        fun encode(drawing: IconDrawing): String =
            buildString {
                append(numberText(drawing.miterLimit))
                for (element in drawing.elements) {
                    append('|')
                    append(
                        when {
                            !element.fill -> '-'
                            element.evenOdd -> 'e'
                            else -> 'n'
                        },
                    )
                    append(if (element.stroke) 's' else '-')
                    append(element.lineCap.first())
                    append(element.lineJoin.first())
                    for (command in element.commands) {
                        when (command) {
                            is PathCommand.Move -> append("M").numbers(command.x, command.y)
                            is PathCommand.Line -> append("L").numbers(command.x, command.y)
                            is PathCommand.Quad -> append("Q").numbers(command.x1, command.y1, command.x, command.y)
                            is PathCommand.Cubic ->
                                append("C").numbers(command.x1, command.y1, command.x2, command.y2, command.x, command.y)
                            PathCommand.Close -> append("Z")
                        }
                    }
                }
            }

        private fun StringBuilder.numbers(vararg values: Double): StringBuilder {
            values.forEachIndexed { index, value ->
                if (index > 0) append(' ')
                append(numberText(value))
            }
            return this
        }
    }
}
