package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.GeneratorError
import com.qeetgroup.qeetrix.gen.KotlinNames
import com.qeetgroup.qeetrix.gen.floatLiteral
import com.qeetgroup.qeetrix.gen.icons.IconDrawing
import com.qeetgroup.qeetrix.gen.icons.PathCommand
import com.qeetgroup.qeetrix.gen.kotlinString

/** One pinned icon: its manifest entry and its drawings by `shape-variant`. */
data class IconSource(
    val name: String,
    val componentName: String,
    val directionality: String,
    val shapes: List<String>,
    val variants: List<String>,
    val drawings: Map<String, IconDrawing>,
)

/**
 * Writes the icon drawings as Compose vector path data under `icons/generated`. The drawings are
 * internal; the public API is the hand-written `QeetrixIconName` and `QeetrixIcon`.
 */
class IconEmitter(
    private val icons: List<IconSource>,
    private val provenance: Provenance,
) {
    fun files(): Map<String, String> {
        val shapes = listOf("round", "sharp")
        val variants = listOf("outline", "filled")
        for (icon in icons) {
            if (!icon.shapes.all { it in shapes } || !icon.variants.all { it in variants }) {
                throw GeneratorError(
                    "${icon.name}: shapes ${icon.shapes} / variants ${icon.variants} include one QeetrixIconShape/Variant does not have.",
                )
            }
            if (icon.directionality !in
                setOf("preserve", "mirror")
            ) {
                throw GeneratorError("${icon.name}: unknown directionality ${icon.directionality}.")
            }
        }
        val names = icons.map { KotlinNames.pascal(listOf(it.name), it.name) to it.name }
        KotlinNames.requireUnique(names, "icons")

        val out = StringBuilder()
        out.appendLine(
            "// GENERATED by qeetrix-gen from ${provenance.iconsRepository}@${provenance.iconsCommit.take(7)} " +
                "(${provenance.iconsPackage} ${provenance.iconsVersion}) — do not edit.",
        )
        out.appendLine("// Add an icon to Upstream/manifest.json, run Scripts/sync-tokens, then Scripts/generate-tokens.")
        out.appendLine()
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import androidx.compose.ui.graphics.StrokeCap")
        out.appendLine("import androidx.compose.ui.graphics.StrokeJoin")
        out.appendLine("import androidx.compose.ui.graphics.vector.PathNode")
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixIconName")
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixIconShape")
        out.appendLine("import com.qeetgroup.qeetrix.icons.QeetrixIconVariant")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixIconDrawing")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixIconElement")
        out.appendLine()
        out.appendLine("/** The upstream (Lucide) name of each icon, as `@qeetrix/icons` spells it. */")
        out.appendLine("internal val QeetrixIconName.upstreamName: String")
        out.appendLine("    get() =")
        out.appendLine("        when (this) {")
        for ((kotlin, upstream) in names) out.appendLine("            QeetrixIconName.$kotlin -> ${kotlinString(upstream)}")
        out.appendLine("        }")
        out.appendLine()
        out.appendLine("/** Whether the drawing mirrors in right-to-left layouts (`directionality: \"mirror\"` upstream). */")
        out.appendLine("internal val QeetrixIconName.mirrorsInRtl: Boolean")
        out.appendLine("    get() =")
        out.appendLine("        when (this) {")
        for ((icon, name) in icons.zip(
            names,
        )) {
            out.appendLine("            QeetrixIconName.${name.first} -> ${icon.directionality == "mirror"}")
        }
        out.appendLine("        }")
        out.appendLine()
        out.appendLine("/** The drawing for a shape and variant, or null when qeetrix-icons does not draw that combination. */")
        out.appendLine("internal fun QeetrixIconName.drawing(shape: QeetrixIconShape, variant: QeetrixIconVariant): QeetrixIconDrawing? =")
        out.appendLine("    when (this) {")
        for ((icon, name) in icons.zip(names)) {
            out.appendLine("        QeetrixIconName.${name.first} ->")
            out.appendLine("            when (shape) {")
            for (shape in shapes) {
                out.appendLine("                QeetrixIconShape.${KotlinNames.pascal(listOf(shape), shape)} ->")
                out.appendLine("                    when (variant) {")
                for (variant in variants) {
                    val key = "$shape-$variant"
                    val target = if (key in icon.drawings) drawingName(name.first, shape, variant) else "null"
                    out.appendLine("                        QeetrixIconVariant.${KotlinNames.pascal(listOf(variant), variant)} -> $target")
                }
                out.appendLine("                    }")
            }
            out.appendLine("            }")
        }
        out.appendLine("    }")

        for ((icon, name) in icons.zip(names)) {
            for (shape in shapes) {
                for (variant in variants) {
                    val drawing = icon.drawings["$shape-$variant"] ?: continue
                    out.appendLine()
                    out.appendLine("// ${icon.name} · $shape-$variant")
                    out.appendLine("private val ${drawingName(name.first, shape, variant)}: QeetrixIconDrawing by lazy {")
                    out.appendLine("    QeetrixIconDrawing(")
                    out.appendLine("        miterLimit = ${floatLiteral(drawing.miterLimit)},")
                    out.appendLine("        elements =")
                    out.appendLine("            listOf(")
                    for (element in drawing.elements) {
                        out.appendLine("                QeetrixIconElement(")
                        out.appendLine("                    fill = ${element.fill},")
                        out.appendLine("                    evenOdd = ${element.evenOdd},")
                        out.appendLine("                    stroke = ${element.stroke},")
                        out.appendLine(
                            "                    cap = StrokeCap.${KotlinNames.pascal(listOf(element.lineCap), element.lineCap)},",
                        )
                        out.appendLine(
                            "                    join = StrokeJoin.${KotlinNames.pascal(listOf(element.lineJoin), element.lineJoin)},",
                        )
                        out.appendLine("                    nodes =")
                        out.appendLine("                        listOf(")
                        for (command in element.commands) out.appendLine("                            ${node(command)},")
                        out.appendLine("                        ),")
                        out.appendLine("                ),")
                    }
                    out.appendLine("            ),")
                    out.appendLine("    )")
                    out.appendLine("}")
                }
            }
        }
        return mapOf("$GENERATED_DIR/QeetrixIconDrawings.kt" to out.toString())
    }

    private fun drawingName(
        icon: String,
        shape: String,
        variant: String,
    ) = icon + KotlinNames.pascal(listOf(shape), shape) + KotlinNames.pascal(listOf(variant), variant)

    private fun node(command: PathCommand): String =
        when (command) {
            is PathCommand.Move -> "PathNode.MoveTo(${f(command.x)}, ${f(command.y)})"

            is PathCommand.Line -> "PathNode.LineTo(${f(command.x)}, ${f(command.y)})"

            is PathCommand.Quad -> "PathNode.QuadTo(${f(command.x1)}, ${f(command.y1)}, ${f(command.x)}, ${f(command.y)})"

            is PathCommand.Cubic -> "PathNode.CurveTo(${f(
                command.x1,
            )}, ${f(command.y1)}, ${f(command.x2)}, ${f(command.y2)}, ${f(command.x)}, ${f(command.y)})"

            PathCommand.Close -> "PathNode.Close"
        }

    private fun f(value: Double) = floatLiteral(value)

    companion object {
        const val PACKAGE = "com.qeetgroup.qeetrix.icons.generated"
        const val GENERATED_DIR = "qeetrix/src/main/kotlin/com/qeetgroup/qeetrix/icons/generated"
    }
}
