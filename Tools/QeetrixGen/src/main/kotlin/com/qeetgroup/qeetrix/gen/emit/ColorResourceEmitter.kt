package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.GeneratorError
import com.qeetgroup.qeetrix.gen.color.ColorMath
import com.qeetgroup.qeetrix.gen.tokens.TokenModel
import com.qeetgroup.qeetrix.gen.tokens.TokenValue

/**
 * The colour roles an app's XML themes need before Compose draws — the window background, the system splash screen —
 * as Android colour resources, light in `values` and dark in `values-night`, from the same tokens as
 * `QeetrixTheme.colors`. Only [ROLES]: everything else is drawn in Compose.
 */
class ColorResourceEmitter(
    private val model: TokenModel,
    private val provenance: Provenance,
) {
    fun files(): Map<String, String> {
        val (light, dark) =
            model.themes.let {
                if (it != listOf("light", "dark")) throw GeneratorError("Colour resources expect the light and dark schemes; found $it.")
                it[0] to it[1]
            }
        return mapOf(
            "$RES_DIR/values/$FILE" to resources(light),
            "$RES_DIR/values-night/$FILE" to resources(dark),
        )
    }

    private fun resources(theme: String): String {
        val out = StringBuilder()
        out.appendLine("<?xml version=\"1.0\" encoding=\"utf-8\"?>")
        out.appendLine(
            "<!-- GENERATED by qeetrix-gen from ${provenance.tokens.packageName} ${provenance.tokens.version} — do not edit. " +
                "Run Scripts/generate-tokens. -->",
        )
        out.appendLine("<!-- The `$theme` scheme of the colour roles an app's XML themes need (window, splash screen). -->")
        out.appendLine("<resources>")
        for (role in ROLES) {
            val token = model.included.firstOrNull { it.dotted == role } ?: throw GeneratorError("$role, a colour resource, is not generated.")
            val color = (token.themes.getValue(theme) as TokenValue.Color).color
            if (color.space != ColorMath.Space.SRGB) {
                throw GeneratorError("$role is outside sRGB in $theme; an Android colour resource can only hold sRGB.")
            }
            out.appendLine("    <color name=\"${resourceName(role)}\">#%08X</color>".format(color.argb))
        }
        out.appendLine("</resources>")
        return out.toString()
    }

    companion object {
        const val RES_DIR = "qeetrix/src/main/res"
        const val FILE = "qx_colors.xml"

        /** The roles published as resources, in this order. */
        val ROLES =
            listOf(
                "color.surface.canvas",
                "color.surface.default",
                "color.surface.raised",
                "color.text.default",
                "color.bg.brand.bold",
            )

        /** `color.surface.default` → `qx_surface_default`. */
        fun resourceName(role: String): String = "qx_" + role.removePrefix("color.").replace('.', '_').replace('-', '_')
    }
}
