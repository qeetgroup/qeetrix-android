package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.color.ColorMath
import com.qeetgroup.qeetrix.gen.round6
import com.qeetgroup.qeetrix.gen.tokens.TokenModel
import com.qeetgroup.qeetrix.gen.tokens.TokenValue
import com.qeetgroup.qeetrix.gen.upstream.Lock
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

/** The generated documentation: the token coverage report and the platform-neutral value table. */
class Reports(
    private val model: TokenModel,
    private val provenance: Provenance,
) {
    fun files(): Map<String, String> =
        mapOf(
            "Documentation/Foundations/TOKEN_COVERAGE.md" to coverage(),
            "Documentation/Foundations/token-values.json" to values(),
        )

    private fun coverage(): String {
        val out = StringBuilder()
        out.appendLine("<!-- GENERATED by qeetrix-gen — do not edit. Run Scripts/generate-tokens. -->")
        out.appendLine()
        out.appendLine("# Token coverage")
        out.appendLine()
        out.appendLine(
            "Source: `${provenance.uiPackage}@${provenance.uiVersion}` (git `${provenance.uiGitHead.take(7)}`), themes " +
                model.themes.joinToString(", ") { "`$it`" } + ".",
        )
        out.appendLine()
        out.appendLine("${model.included.size} tokens are generated as Kotlin; ${model.excluded.size} are not. The rule is in")
        out.appendLine(
            "[`Tools/QeetrixGen/src/main/kotlin/com/qeetgroup/qeetrix/gen/tokens/Scope.kt`](../../Tools/QeetrixGen/src/main/kotlin/com/qeetgroup/qeetrix/gen/tokens/Scope.kt).",
        )
        out.appendLine()
        out.appendLine("## Generated")
        out.appendLine()
        out.appendLine("| Group | Tokens | Public Kotlin API |")
        out.appendLine("|:--|--:|:--|")
        val groups =
            listOf(
                listOf("color") to "`QeetrixColors` (`QeetrixTheme.colors`)",
                listOf("elevation") to "`QeetrixElevation`",
                listOf("typography") to "`QeetrixTextRole`, `QeetrixTypography` (`QeetrixTheme.typography`)",
                listOf("font", "weight") to "`QeetrixFontWeight`",
                listOf("font", "geometry") to "`QeetrixFontGeometry`",
                listOf("space") to "`QeetrixSpacing`",
                listOf("corner") to "`QeetrixCorner`, `QeetrixShapes`",
                listOf("stroke", "width") to "`QeetrixStroke`",
                listOf("focus") to "`QeetrixFocus`",
                listOf("state", "opacity") to "`QeetrixOpacity`",
                listOf("icon", "size") to "`QeetrixIconSize`",
                listOf("icon", "stroke") to "`QeetrixIconStroke`",
                listOf("density") to "`QeetrixDensity`",
                listOf("motion") to "`QeetrixDuration`, `QeetrixEasing`, `QeetrixMotion`",
            )
        for ((prefix, api) in groups) {
            val count = model.tokensUnder(*prefix.toTypedArray()).size
            if (count > 0) out.appendLine("| `${prefix.joinToString(".")}` | $count | $api |")
        }
        out.appendLine()
        out.appendLine("## Not generated")
        out.appendLine()
        out.appendLine("| Reason | Tokens | Examples |")
        out.appendLine("|:--|--:|:--|")
        for ((reason, tokens) in model.excluded.groupBy { it.reason }) {
            val examples = tokens.take(3).joinToString(", ") { "`${it.path.joinToString(".")}`" } + if (tokens.size > 3) ", …" else ""
            out.appendLine("| $reason | ${tokens.size} | $examples |")
        }
        val outside =
            model.tokensUnder("color").flatMap { token ->
                model.themes.mapNotNull { theme ->
                    val color = (token.values.getValue(theme) as TokenValue.Color).color
                    if (color.space == ColorMath.Space.SRGB) null else Triple(token.dotted, theme, color)
                }
            }
        if (outside.isNotEmpty()) {
            out.appendLine()
            out.appendLine("## Colours outside sRGB")
            out.appendLine()
            out.appendLine(
                "These convert outside sRGB and are emitted in Display P3, as a browser paints them on a P3 display. Android draws them " +
                    "in P3 in a window with `colorMode=\"wideColorGamut\"` on a wide-gamut display, and converts them to sRGB elsewhere.",
            )
            out.appendLine()
            out.appendLine("| Token | Theme | Handling |")
            out.appendLine("|:--|:--|:--|")
            for ((path, theme, color) in outside) {
                out.appendLine(
                    "| `$path` | $theme | ${if (color.gamutMapped) "outside P3 — gamut-mapped to Display P3" else "inside P3 — drawn in Display P3"} |",
                )
            }
        }
        return out.toString()
    }

    /**
     * Every generated token's value per theme, with the CSS expression it was computed from — the
     * comparison surface for another platform's generator, and colour-conversion test vectors.
     */
    private fun values(): String {
        val tokens = LinkedHashMap<String, JsonElement>()
        for (token in model.included) {
            val perTheme = LinkedHashMap<String, JsonElement>()
            for (theme in model.themes) {
                perTheme[theme] =
                    JsonObject(
                        linkedMapOf(
                            "input" to JsonPrimitive(token.inputs.getValue(theme)),
                            "value" to json(token.values.getValue(theme)),
                        ),
                    )
            }
            tokens[token.dotted] =
                JsonObject(linkedMapOf("kind" to JsonPrimitive(token.kind.name.lowercase()), "themes" to JsonObject(perTheme)))
        }
        val root =
            JsonObject(
                linkedMapOf(
                    "\$comment" to
                        JsonPrimitive(
                            "GENERATED by qeetrix-gen — do not edit. Every token qeetrix-android generates, per theme: the CSS expression after var() substitution and the resolved value. Colours: CSS Color 4 conversion, sRGB when inside sRGB, else Display P3 (gamut-mapped per CSS Color 4 §13.2 if outside P3), components gamma-encoded and rounded to six decimals. Lengths in dp (1 CSS px = 1 dp, 1rem = 16 dp); durations in ms.",
                        ),
                    "source" to
                        JsonObject(
                            linkedMapOf(
                                "package" to JsonPrimitive(provenance.uiPackage),
                                "version" to JsonPrimitive(provenance.uiVersion),
                                "gitHead" to JsonPrimitive(provenance.uiGitHead),
                            ),
                        ),
                    "themes" to JsonArray(model.themes.map(::JsonPrimitive)),
                    "tokens" to JsonObject(tokens),
                ),
            )
        return Lock.pretty.encodeToString(JsonObject.serializer(), root) + "\n"
    }

    private fun json(value: TokenValue): JsonElement =
        when (value) {
            is TokenValue.Color -> {
                color(value.color)
            }

            is TokenValue.Dimension -> {
                JsonObject(linkedMapOf("dp" to number(value.dp)))
            }

            is TokenValue.Em -> {
                JsonObject(linkedMapOf("em" to number(value.em)))
            }

            is TokenValue.Number -> {
                number(value.value)
            }

            is TokenValue.Duration -> {
                JsonObject(linkedMapOf("ms" to number(value.millis)))
            }

            is TokenValue.Easing -> {
                JsonObject(linkedMapOf("cubicBezier" to JsonArray(value.points.map(::number))))
            }

            is TokenValue.FontFamily -> {
                JsonPrimitive(value.name)
            }

            is TokenValue.Shadow -> {
                JsonArray(
                    value.layers.map {
                        JsonObject(
                            linkedMapOf(
                                "inset" to JsonPrimitive(it.inset),
                                "x" to number(it.x),
                                "y" to number(it.y),
                                "blur" to number(it.blur),
                                "spread" to number(it.spread),
                                "color" to color(it.color),
                            ),
                        )
                    },
                )
            }
        }

    private fun color(color: ColorMath.EncodedColor): JsonElement =
        JsonObject(
            linkedMapOf(
                "space" to JsonPrimitive(color.space.id),
                "rgba" to JsonArray(listOf(color.red, color.green, color.blue, color.alpha).map(::number)),
                "srgbHex" to JsonPrimitive(color.hex),
                "gamutMapped" to if (color.gamutMapped) JsonPrimitive(true) else JsonNull,
            ).filterValues { it != JsonNull },
        )

    private fun number(value: Double): JsonPrimitive {
        val rounded = round6(value)
        return if (rounded == Math.rint(rounded)) JsonPrimitive(rounded.toLong()) else JsonPrimitive(rounded)
    }
}
