package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.color.ColorMath
import com.qeetgroup.qeetrix.gen.round6
import com.qeetgroup.qeetrix.gen.tokens.TokenKind
import com.qeetgroup.qeetrix.gen.tokens.TokenModel
import com.qeetgroup.qeetrix.gen.tokens.TokenValue
import com.qeetgroup.qeetrix.gen.upstream.Lock
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

/** The generated documentation: the token coverage report and the platform-neutral value table. */
class Reports(
    private val model: TokenModel,
    private val provenance: Provenance,
) {
    fun files(): Map<String, String> =
        mapOf(
            "docs/tokens.md" to coverage(),
            "docs/token-values.json" to values(),
        )

    /** Colours whose 8-bit sRGB rendition differs from the `hex` @qeetrix/tokens records beside it. */
    private fun hexDisagreements(): List<String> =
        model.included
            .filter { it.kind == TokenKind.COLOR }
            .flatMap { token ->
                token.themes.mapNotNull { (theme, value) ->
                    val color = value as TokenValue.Color
                    val ours = color.color.hex.take(7).lowercase()
                    val theirs = color.dtcgHex?.lowercase() ?: return@mapNotNull null
                    if (ours == theirs) null else "| `${token.dotted}` | $theme | `$ours` | `$theirs` |"
                }
            }

    private fun coverage(): String {
        val tokens = provenance.tokens
        val out = StringBuilder()
        out.appendLine("<!-- GENERATED by qeetrix-gen — do not edit. Run Scripts/generate-tokens. -->")
        out.appendLine()
        out.appendLine("# Token coverage")
        out.appendLine()
        out.appendLine(
            "Source: `${tokens.packageName}@${tokens.version}` (git `${tokens.gitHead.take(7)}`), its DTCG build resolved as " +
                "`qeetrix.resolver.json` says: colour schemes " + model.themes.joinToString(", ") { "`$it`" } +
                " at the `${model.defaultDensity}` density, and densities " + model.densities.joinToString(", ") { "`$it`" } + ".",
        )
        out.appendLine()
        out.appendLine("${model.included.size} tokens are generated as Kotlin; ${model.excluded.size} are not. The rule is in")
        out.appendLine(
            "[`Tools/QeetrixGen/src/main/kotlin/com/qeetgroup/qeetrix/gen/tokens/Scope.kt`](../Tools/QeetrixGen/src/main/kotlin/com/qeetgroup/qeetrix/gen/tokens/Scope.kt);",
        )
        out.appendLine("every value, with the DTCG token it came from, is in [token-values.json](token-values.json).")
        out.appendLine()
        out.appendLine("## Generated")
        out.appendLine()
        out.appendLine("| Token | Kotlin |")
        out.appendLine("|:--|:--|")
        for (token in model.included) out.appendLine("| `${token.dotted}` | `${TokenEmitter.publicAccessor(model, token)}` |")
        out.appendLine()
        out.appendLine("## Not generated")
        out.appendLine()
        out.appendLine("| Reason | Tokens | Examples |")
        out.appendLine("|:--|--:|:--|")
        for ((reason, excluded) in model.excluded.groupBy { it.reason }) {
            val examples = excluded.take(3).joinToString(", ") { "`${it.path.joinToString(".")}`" } + if (excluded.size > 3) ", …" else ""
            out.appendLine("| $reason | ${excluded.size} | $examples |")
        }
        val outside =
            model.tokensUnder("color").flatMap { token ->
                model.themes.mapNotNull { theme ->
                    val color = (token.themes.getValue(theme) as TokenValue.Color).color
                    if (color.space == ColorMath.Space.SRGB) null else Triple(token.dotted, theme, color)
                }
            }
        if (outside.isNotEmpty()) {
            out.appendLine()
            out.appendLine("## Colours outside sRGB")
            out.appendLine()
            out.appendLine(
                "These convert outside sRGB and are emitted in Display P3, as a browser paints them on a P3 display. Android draws them " +
                    "in P3 in a window with `colorMode=\"wideColorGamut\"` on a wide-gamut display, and converts them to sRGB elsewhere.",
            )
            out.appendLine()
            out.appendLine("| Token | Theme | Handling |")
            out.appendLine("|:--|:--|:--|")
            for ((path, theme, color) in outside) {
                out.appendLine(
                    "| `$path` | $theme | ${if (color.gamutMapped) "outside P3 — gamut-mapped to Display P3" else "inside P3 — drawn in Display P3"} |",
                )
            }
        }
        val disagreements = hexDisagreements()
        out.appendLine()
        out.appendLine("## Cross-check against the recorded hex")
        out.appendLine()
        if (disagreements.isEmpty()) {
            out.appendLine(
                "Every colour's 8-bit sRGB rendition, converted here from its OKLCH components per CSS Color 4, equals the `hex` " +
                    "${tokens.packageName} records beside it.",
            )
        } else {
            out.appendLine("These colours' sRGB rendition differs from the `hex` ${tokens.packageName} records beside them:")
            out.appendLine()
            out.appendLine("| Token | Theme | Converted | Recorded |")
            out.appendLine("|:--|:--|:--|:--|")
            disagreements.forEach(out::appendLine)
        }
        return out.toString()
    }

    /**
     * Every generated token's value per colour scheme (and per density, for the tokens density changes),
     * with the DTCG token it was resolved from — the comparison surface for qeetrix-ios's generator, which
     * writes the same file. Platform-neutral: lengths in CSS px, durations in ms, colours as encoded RGB.
     */
    private fun values(): String {
        val tokens = LinkedHashMap<String, JsonElement>()
        for (token in model.included) {
            val perTheme = LinkedHashMap<String, JsonElement>()
            for (theme in model.themes) {
                val source = token.sources.getValue(theme)
                perTheme[theme] =
                    JsonObject(
                        linkedMapOf(
                            "source" to JsonPrimitive(source.source),
                            "authored" to source.raw,
                            "references" to JsonArray(source.chain.map(::JsonPrimitive)),
                            "value" to json(token.themes.getValue(theme)),
                        ),
                    )
            }
            val entry =
                linkedMapOf<String, JsonElement>(
                    "type" to JsonPrimitive(token.kind.dtcgType),
                    "themes" to JsonObject(perTheme),
                )
            token.densities?.let { densities -> entry["densities"] = JsonObject(densities.mapValues { json(it.value) }) }
            tokens[token.dotted] = JsonObject(entry)
        }
        val root =
            JsonObject(
                linkedMapOf(
                    "\$comment" to
                        JsonPrimitive(
                            "GENERATED by qeetrix-gen — do not edit. Every token qeetrix-android generates from @qeetrix/tokens' DTCG build, resolved as qeetrix.resolver.json says: per colour scheme at the default density, and per density for the tokens density changes. For each: the source file whose definition won, the value as authored there, the references followed, and the resolved value. Colours: OKLCH converted per CSS Color 4, sRGB when inside sRGB, else Display P3 (gamut-mapped per CSS Color 4 §13.2 if outside P3), components gamma-encoded and rounded to six decimals. Lengths in CSS px (1rem = 16px; Android draws 1px as 1dp); durations in ms; letter spacing in em.",
                        ),
                    "source" to provenance.tokens.toJson(),
                    "resolver" to JsonPrimitive("qeetrix.resolver.json"),
                    "themes" to JsonArray(model.themes.map(::JsonPrimitive)),
                    "densities" to JsonArray(model.densities.map(::JsonPrimitive)),
                    "defaultDensity" to JsonPrimitive(model.defaultDensity),
                    "tokens" to JsonObject(tokens),
                ),
            )
        return Lock.pretty.encodeToString(JsonObject.serializer(), root) + "\n"
    }

    private fun json(value: TokenValue): JsonElement =
        when (value) {
            is TokenValue.Color -> {
                color(value.color)
            }

            is TokenValue.Dimension -> {
                JsonObject(linkedMapOf("px" to number(value.px)))
            }

            is TokenValue.Number -> {
                number(value.value)
            }

            is TokenValue.Duration -> {
                JsonObject(linkedMapOf("ms" to number(value.millis)))
            }

            is TokenValue.Easing -> {
                JsonObject(linkedMapOf("cubicBezier" to JsonArray(value.points.map(::number))))
            }

            is TokenValue.FontFamily -> {
                JsonArray(value.names.map(::JsonPrimitive))
            }

            is TokenValue.Typography -> {
                JsonObject(
                    linkedMapOf(
                        "fontFamily" to JsonPrimitive(value.family),
                        "fontSize" to JsonObject(linkedMapOf("px" to number(value.sizePx))),
                        "fontWeight" to JsonPrimitive(value.weight),
                        "lineHeight" to number(value.lineHeight),
                        "lineHeightLength" to JsonObject(linkedMapOf("px" to number(value.lineHeightPx))),
                        "letterSpacing" to JsonObject(linkedMapOf("em" to number(value.letterSpacingEm))),
                        "fontGeometry" to JsonPrimitive(value.geometry.joinToString(".")),
                    ),
                )
            }

            is TokenValue.Shadow -> {
                JsonArray(
                    value.layers.map {
                        JsonObject(
                            linkedMapOf(
                                "inset" to JsonPrimitive(it.inset),
                                "x" to number(it.x),
                                "y" to number(it.y),
                                "blur" to number(it.blur),
                                "spread" to number(it.spread),
                                "color" to color(it.color),
                            ),
                        )
                    },
                )
            }
        }

    private fun color(color: ColorMath.EncodedColor): JsonElement =
        JsonObject(
            linkedMapOf(
                "space" to JsonPrimitive(color.space.id),
                "rgba" to JsonArray(listOf(color.red, color.green, color.blue, color.alpha).map(::number)),
                "srgbHex" to JsonPrimitive(color.hex),
                "gamutMapped" to if (color.gamutMapped) JsonPrimitive(true) else JsonNull,
            ).filterValues { it != JsonNull },
        )

    private fun number(value: Double): JsonPrimitive {
        val rounded = round6(value)
        return if (rounded == Math.rint(rounded)) JsonPrimitive(rounded.toLong()) else JsonPrimitive(rounded)
    }
}
