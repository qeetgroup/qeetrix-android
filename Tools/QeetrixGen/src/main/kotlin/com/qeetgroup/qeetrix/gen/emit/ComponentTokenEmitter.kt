package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.GeneratorError
import com.qeetgroup.qeetrix.gen.KotlinNames
import com.qeetgroup.qeetrix.gen.color.ColorMath
import com.qeetgroup.qeetrix.gen.floatLiteral
import com.qeetgroup.qeetrix.gen.numberText
import com.qeetgroup.qeetrix.gen.tokens.ResolvedToken
import com.qeetgroup.qeetrix.gen.tokens.TokenModel
import com.qeetgroup.qeetrix.gen.tokens.TokenValue

/**
 * Writes one internal `Qeetrix<Group>ComponentTokens` object per adopted `component.<group>`, in the
 * same package as the other generated tokens. The rule is qeetrix-ios's (its ADR 0011):
 *
 * - a colour that names the same semantic colour in every theme is generated as that semantic colour,
 *   read from the current theme, so it follows the theme;
 * - a colour that differs by theme in any other way (a `color-mix`, a reference in one theme only) is
 *   generated as a value per theme;
 * - a size that follows the density is a function of `QeetrixDensity`; an elevation is a
 *   `QeetrixElevation`; lengths, percentages and em values are constants;
 * - a non-colour value that differs by theme fails generation — no component needs one, and picking a
 *   theme silently would be wrong.
 */
class ComponentTokenEmitter(
    private val model: TokenModel,
    private val provenance: Provenance,
) {
    fun files(): Map<String, String> =
        model.adoptedComponents.sorted().associate { group ->
            "${TokenEmitter.GENERATED_DIR}/${objectName(group)}.kt" to file(group, model.tokensUnder("component", group))
        }

    private fun file(
        group: String,
        tokens: List<ResolvedToken>,
    ): String {
        val names = tokens.map { KotlinNames.pascal(it.path.drop(2), it.dotted) to it.dotted }
        KotlinNames.requireUnique(names, "component.$group")
        val members = tokens.zip(names).map { (token, name) -> member(token, name.first) }
        val body = members.joinToString("\n\n") { it.text }
        val imports = (members.flatMap { it.imports } + "androidx.compose.runtime.Immutable").toSortedSet()

        val out = StringBuilder()
        out.appendLine(
            "// GENERATED by qeetrix-gen from ${provenance.uiPackage} ${provenance.uiVersion} (git ${provenance.uiGitHead.take(
                7,
            )}) — do not edit.",
        )
        out.appendLine(
            "// Adopt or drop a component group in Upstream/manifest.json (qeetrixUI.componentTokens), then Scripts/generate-tokens.",
        )
        out.appendLine("package ${TokenEmitter.PACKAGE}")
        out.appendLine()
        for (import in imports) out.appendLine("import $import")
        out.appendLine()
        out.appendLine("/** `component.$group.*` — the $group components' own tokens. Internal: components read them, apps do not. */")
        out.appendLine("@Immutable")
        out.appendLine("internal object ${objectName(group)} {")
        out.appendLine(body.lines().joinToString("\n") { if (it.isBlank()) "" else "    $it" })
        out.appendLine("}")
        return out.toString()
    }

    private class Member(
        val text: String,
        val imports: List<String>,
    )

    private fun member(
        token: ResolvedToken,
        name: String,
    ): Member {
        val values = model.themes.map { token.values.getValue(it) }
        val first = values.first()
        val raws = model.themes.map { token.raws.getValue(it) }
        val doc =
            if (raws.toSet().size == 1) {
                "/** `${token.dotted}` = `${raws[0]}` */"
            } else {
                "/** `${token.dotted}` = `${raws[0]}` in light, `${raws[1]}` in dark */"
            }
        val theme = "com.qeetgroup.qeetrix.theme.QeetrixTheme"
        val composable = listOf("androidx.compose.runtime.Composable", "androidx.compose.runtime.ReadOnlyComposable", theme)
        val color = "androidx.compose.ui.graphics.Color"

        // A semantic colour named in every theme: read it from the theme.
        if (values.all { it is TokenValue.ColorRef && it.path == (first as? TokenValue.ColorRef)?.path }) {
            val property = KotlinNames.camel((first as TokenValue.ColorRef).path.split('.').drop(1), first.path)
            return Member(
                "$doc\nval $name: Color\n    @Composable @ReadOnlyComposable\n    get() = QeetrixTheme.colors.$property",
                composable + color,
            )
        }
        // Colours that differ by theme otherwise: a value per theme.
        if (values.all { it is TokenValue.Color || it is TokenValue.ColorRef }) {
            val encoded = values.map { if (it is TokenValue.Color) it.color else (it as TokenValue.ColorRef).resolved }
            if (model.themes !=
                listOf("light", "dark")
            ) {
                throw GeneratorError("${token.dotted}: per-theme colours need a mapping for ${model.themes}.")
            }
            val colorSpaces =
                if (encoded.any {
                        it.space == ColorMath.Space.DISPLAY_P3
                    }
                ) {
                    listOf("androidx.compose.ui.graphics.colorspace.ColorSpaces")
                } else {
                    emptyList()
                }
            if (encoded.toSet().size == 1) {
                return Member("$doc\nval $name: Color = ${TokenEmitter.colorLiteral(encoded[0])}", listOf(color) + colorSpaces)
            }
            val imports = composable + color + colorSpaces
            return Member(
                "$doc\nval $name: Color\n    @Composable @ReadOnlyComposable\n" +
                    "    get() = if (QeetrixTheme.isDark) ${TokenEmitter.colorLiteral(
                        encoded[1],
                    )} else ${TokenEmitter.colorLiteral(encoded[0])}",
                imports,
            )
        }
        if (!token.isThemeInvariant) {
            throw GeneratorError("${token.dotted}: a ${first::class.simpleName} that varies by theme; no Android mapping exists for that.")
        }
        return when (first) {
            is TokenValue.ElevationRef -> {
                val entry = KotlinNames.pascal(first.path.split('.').drop(1), first.path)
                Member(
                    "$doc\nval $name: QeetrixElevation = QeetrixElevation.$entry",
                    listOf("com.qeetgroup.qeetrix.foundation.elevation.QeetrixElevation"),
                )
            }

            is TokenValue.DensityRef -> {
                val property = KotlinNames.camel(listOf(first.metric), first.metric)
                Member(
                    "$doc\nfun ${name.replaceFirstChar(Char::lowercaseChar)}(density: QeetrixDensity): Dp = density.$property",
                    listOf("com.qeetgroup.qeetrix.foundation.sizing.QeetrixDensity", "androidx.compose.ui.unit.Dp"),
                )
            }

            is TokenValue.Dimension -> {
                Member(
                    "$doc\nval $name: Dp = ${TokenEmitter.dp(first.dp)}",
                    listOf("androidx.compose.ui.unit.Dp", "androidx.compose.ui.unit.dp"),
                )
            }

            is TokenValue.Em -> {
                Member(
                    "$doc\nval $name: TextUnit = ${numberText(first.em)}.em",
                    listOf("androidx.compose.ui.unit.TextUnit", "androidx.compose.ui.unit.em"),
                )
            }

            is TokenValue.Percent -> {
                Member("$doc\nval $name: Float = ${floatLiteral(first.fraction)} // of the element's own size", emptyList())
            }

            is TokenValue.Number -> {
                Member("$doc\nval $name: Float = ${floatLiteral(first.value)}", emptyList())
            }

            else -> {
                throw GeneratorError("${token.dotted}: a ${first::class.simpleName} component token has no Android mapping yet.")
            }
        }
    }

    companion object {
        fun objectName(group: String): String = "Qeetrix${KotlinNames.pascal(listOf(group), group)}ComponentTokens"
    }
}
