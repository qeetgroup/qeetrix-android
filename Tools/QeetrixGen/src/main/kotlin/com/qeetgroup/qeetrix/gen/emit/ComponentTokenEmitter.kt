package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.GeneratorError
import com.qeetgroup.qeetrix.gen.KotlinNames
import com.qeetgroup.qeetrix.gen.numberText
import com.qeetgroup.qeetrix.gen.tokens.ResolvedToken
import com.qeetgroup.qeetrix.gen.tokens.TokenModel
import com.qeetgroup.qeetrix.gen.tokens.TokenValue

/**
 * Writes one internal `Qeetrix<Group>ComponentTokens` object per adopted `component.<group>`, in the
 * same package as the other generated tokens. `@qeetrix/tokens` keeps only the component decisions no
 * semantic token covers (sidebar widths, the timeline marker, …), all of them lengths, so each is a `Dp`
 * constant; one that varied by colour scheme or density would fail generation.
 */
class ComponentTokenEmitter(
    private val model: TokenModel,
    private val provenance: Provenance,
) {
    fun files(): Map<String, String> =
        model.adoptedComponents.sorted().associate { group ->
            "${TokenEmitter.GENERATED_DIR}/${objectName(group)}.kt" to file(group, model.tokensUnder("component", group))
        }

    private fun file(
        group: String,
        tokens: List<ResolvedToken>,
    ): String {
        val names = tokens.map { KotlinNames.pascal(it.path.drop(2), it.dotted) to it.dotted }
        KotlinNames.requireUnique(names, "component.$group")
        val out = StringBuilder()
        out.appendLine(
            "// GENERATED by qeetrix-gen from ${provenance.tokens.packageName} ${provenance.tokens.version} " +
                "(git ${provenance.tokens.gitHead.take(7)}) — do not edit.",
        )
        out.appendLine("// Change the upstream tokens, bump Upstream/manifest.json, run Scripts/sync-tokens, then Scripts/generate-tokens.")
        out.appendLine()
        out.appendLine("package ${TokenEmitter.PACKAGE}")
        out.appendLine()
        out.appendLine("import androidx.compose.ui.unit.Dp")
        out.appendLine("import androidx.compose.ui.unit.dp")
        out.appendLine()
        out.appendLine("/** `component.$group.*`, in dp. */")
        out.appendLine("internal object ${objectName(group)} {")
        for ((token, name) in tokens.zip(names)) {
            if (!token.isThemeInvariant || token.followsDensity) {
                throw GeneratorError("${token.dotted}: a component token that varies by colour scheme or density.")
            }
            val value = token.themes.values.first() as? TokenValue.Dimension ?: throw GeneratorError("${token.dotted}: not a length.")
            out.appendLine("    /** `${token.dotted}` — ${numberText(value.px)}px. */")
            out.appendLine("    val ${name.first}: Dp = ${TokenEmitter.dp(value.px)}")
        }
        out.appendLine("}")
        return out.toString()
    }

    companion object {
        fun objectName(group: String): String = "Qeetrix${KotlinNames.pascal(listOf(group), group)}ComponentTokens"
    }
}
