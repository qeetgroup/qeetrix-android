package com.qeetgroup.qeetrix.gen.emit

import com.qeetgroup.qeetrix.gen.GeneratorError
import com.qeetgroup.qeetrix.gen.KotlinNames
import com.qeetgroup.qeetrix.gen.color.ColorMath
import com.qeetgroup.qeetrix.gen.floatLiteral
import com.qeetgroup.qeetrix.gen.kotlinString
import com.qeetgroup.qeetrix.gen.numberText
import com.qeetgroup.qeetrix.gen.tokens.CssValues
import com.qeetgroup.qeetrix.gen.tokens.ResolvedToken
import com.qeetgroup.qeetrix.gen.tokens.TokenKind
import com.qeetgroup.qeetrix.gen.tokens.TokenModel
import com.qeetgroup.qeetrix.gen.tokens.TokenValue

/** A bundled font: the pin that produced it plus what the file says about itself. */
data class FontSpec(
    /** `sans` or `mono`: the family key the typography roles use. */
    val family: String,
    val webFamily: String,
    val repository: String,
    val tag: String,
    /** The Android resource name, e.g. `qx_cal_sans_vf`. */
    val resourceName: String,
    val sha256: String,
    val info: com.qeetgroup.qeetrix.gen.fonts.FontInfo,
)

/** Where the generated tokens came from, written into headers and the provenance object. */
data class Provenance(
    val uiPackage: String,
    val uiVersion: String,
    val uiGitHead: String,
    val uiIntegrity: String,
    val iconsRepository: String,
    val iconsPackage: String,
    val iconsVersion: String,
    val iconsCommit: String,
)

/**
 * Writes the resolved token model as Kotlin under `tokens/generated`. Every declaration is `internal`:
 * the public API is the hand-written foundation and theme types, which these files construct.
 */
class TokenEmitter(
    private val model: TokenModel,
    private val provenance: Provenance,
    private val fonts: List<FontSpec>,
) {
    private val header =
        """
        |// GENERATED by qeetrix-gen from ${provenance.uiPackage} ${provenance.uiVersion} (git ${provenance.uiGitHead.take(
            7,
        )}) — do not edit.
        |// Change the upstream tokens, bump Upstream/manifest.json, run Scripts/sync-tokens, then Scripts/generate-tokens.
        |
        """.trimMargin()

    private val themeNames: Map<String, String> = model.themes.associateWith { KotlinNames.pascal(listOf(it), "theme $it") }

    /** One generated scale object: the tokens under [prefix], typed as [type]. */
    private class ScaleGroup(
        val prefix: List<String>,
        val objectName: String,
        val type: ScaleType,
        val doc: String,
    )

    private enum class ScaleType { DP, FLOAT, INT, MOTION }

    private val scaleGroups =
        listOf(
            ScaleGroup(listOf("space"), "QeetrixSpaceTokens", ScaleType.DP, "`space.*` — the spacing scale, in dp."),
            ScaleGroup(listOf("corner"), "QeetrixCornerTokens", ScaleType.DP, "`corner.*` — corner radii, in dp."),
            ScaleGroup(
                listOf("stroke", "width"),
                "QeetrixStrokeWidthTokens",
                ScaleType.DP,
                "`stroke.width.*` — border and divider widths, in dp.",
            ),
            ScaleGroup(listOf("focus"), "QeetrixFocusTokens", ScaleType.DP, "`focus.*` — focus indicator geometry, in dp."),
            ScaleGroup(listOf("state", "opacity"), "QeetrixOpacityTokens", ScaleType.FLOAT, "`state.opacity.*` — state opacities, 0–1."),
            ScaleGroup(listOf("icon", "size"), "QeetrixIconSizeTokens", ScaleType.DP, "`icon.size.*` — icon box sizes, in dp."),
            ScaleGroup(
                listOf("icon", "stroke"),
                "QeetrixIconStrokeTokens",
                ScaleType.FLOAT,
                "`icon.stroke.*` — icon stroke widths, in 24-unit grid units.",
            ),
            ScaleGroup(
                listOf("font", "weight"),
                "QeetrixFontWeightTokens",
                ScaleType.INT,
                "`font.weight.*` — the weight scale (the `wght` axis).",
            ),
            ScaleGroup(
                listOf("font", "geometry"),
                "QeetrixFontGeometryTokens",
                ScaleType.FLOAT,
                "`font.geometry.*` — Qeet Sans's letter styles (the `GEOM` axis).",
            ),
            ScaleGroup(listOf("density"), "QeetrixDensityTokens", ScaleType.DP, "`density.*` — control metrics per density, in dp."),
            ScaleGroup(
                listOf("motion"),
                "QeetrixMotionTokens",
                ScaleType.MOTION,
                "`motion.*` — durations in milliseconds and easing curves.",
            ),
        )

    fun files(): Map<String, String> {
        val claimed = HashSet<String>()

        fun claim(tokens: List<ResolvedToken>) = tokens.forEach { claimed += it.dotted }
        val files =
            linkedMapOf(
                "QeetrixColorTokens.kt" to colors().also { claim(model.tokensUnder("color")) },
                "QeetrixElevationTokens.kt" to elevation().also { claim(model.tokensUnder("elevation")) },
                "QeetrixTypographyTokens.kt" to typography().also { claim(model.tokensUnder("typography")) },
                "QeetrixScaleTokens.kt" to scales().also { scaleGroups.forEach { claim(model.tokensUnder(*it.prefix.toTypedArray())) } },
                "QeetrixProvenanceTokens.kt" to provenanceFile(),
            )
        val unclaimed = model.included.filter { it.dotted !in claimed && it.kind != TokenKind.COMPONENT }
        if (unclaimed.isNotEmpty()) {
            throw GeneratorError("No Kotlin home for ${unclaimed.joinToString { it.dotted }}. Map the group in TokenEmitter.")
        }
        return files.mapKeys { "$GENERATED_DIR/${it.key}" }
    }

    // Colours

    private fun colors(): String {
        val tokens = model.tokensUnder("color")
        val names = tokens.map { KotlinNames.camel(it.path.drop(1), it.dotted) to it.dotted }
        KotlinNames.requireUnique(names, "color")
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import androidx.compose.ui.graphics.Color")
        if (tokens.any { token -> token.values.values.any { (it as TokenValue.Color).color.space == ColorMath.Space.DISPLAY_P3 } }) {
            out.appendLine("import androidx.compose.ui.graphics.colorspace.ColorSpaces")
        }
        out.appendLine("import com.qeetgroup.qeetrix.foundation.color.QeetrixColors")
        for (theme in model.themes) {
            out.appendLine()
            out.appendLine("/** The `$theme` theme's semantic colours: every `color.*` token in qeetrix-ui's consumable layer. */")
            out.appendLine("internal val Qeetrix${themeNames.getValue(theme)}Colors: QeetrixColors =")
            out.appendLine("    QeetrixColors(")
            for ((token, name) in tokens.zip(names)) {
                val color = (token.values.getValue(theme) as TokenValue.Color).color
                out.appendLine("        // ${token.dotted} · ${describe(color)}")
                out.appendLine("        ${name.first} = ${colorLiteral(color)},")
            }
            out.appendLine("    )")
        }
        out.appendLine()
        out.appendLine("/** Every colour token's upstream path and its accessor, in upstream order. */")
        out.appendLine("internal val QeetrixColorTokenPaths: List<Pair<String, (QeetrixColors) -> Color>> =")
        out.appendLine("    listOf(")
        for ((token, name) in tokens.zip(names)) out.appendLine("        ${kotlinString(token.dotted)} to QeetrixColors::${name.first},")
        out.appendLine("    )")
        return out.toString()
    }

    // Elevation

    private fun elevation(): String {
        val tokens = model.tokensUnder("elevation")
        val names = tokens.map { KotlinNames.pascal(it.path.drop(1), it.dotted) to it.dotted }
        KotlinNames.requireUnique(names, "elevation")
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import androidx.compose.ui.graphics.Color")
        if (tokens.any { token ->
                token.values.values.any { v ->
                    (v as TokenValue.Shadow).layers.any {
                        it.color.space ==
                            ColorMath.Space.DISPLAY_P3
                    }
                }
            }
        ) {
            out.appendLine("import androidx.compose.ui.graphics.colorspace.ColorSpaces")
        }
        out.appendLine("import androidx.compose.ui.unit.dp")
        out.appendLine("import com.qeetgroup.qeetrix.foundation.elevation.QeetrixElevation")
        out.appendLine("import com.qeetgroup.qeetrix.foundation.elevation.QeetrixShadowLayer")
        for (theme in model.themes) {
            val themeName = themeNames.getValue(theme)
            out.appendLine()
            out.appendLine("/** The `$theme` theme's shadow layers, in CSS order: the first layer is drawn on top. */")
            out.appendLine(
                "internal fun QeetrixElevation.${themeName.replaceFirstChar(Char::lowercaseChar)}Layers(): List<QeetrixShadowLayer> =",
            )
            out.appendLine("    when (this) {")
            for ((_, name) in tokens.zip(names)) out.appendLine("        QeetrixElevation.${name.first} -> $themeName${name.first}")
            out.appendLine("    }")
        }
        for (theme in model.themes) {
            val themeName = themeNames.getValue(theme)
            for ((token, name) in tokens.zip(names)) {
                val layers = (token.values.getValue(theme) as TokenValue.Shadow).layers
                out.appendLine()
                out.appendLine("// ${token.dotted} ($theme)")
                if (layers.isEmpty()) {
                    out.appendLine("private val $themeName${name.first}: List<QeetrixShadowLayer> = emptyList()")
                    continue
                }
                out.appendLine("private val $themeName${name.first}: List<QeetrixShadowLayer> =")
                out.appendLine("    listOf(")
                for (layer in layers) out.appendLine("        ${shadowLiteral(layer)},")
                out.appendLine("    )")
            }
        }
        out.appendLine()
        out.appendLine("/** Every elevation token's upstream path, in upstream order. */")
        out.appendLine("internal val QeetrixElevationTokenPaths: List<Pair<String, QeetrixElevation>> =")
        out.appendLine("    listOf(")
        for ((token, name) in tokens.zip(names)) out.appendLine("        ${kotlinString(token.dotted)} to QeetrixElevation.${name.first},")
        out.appendLine("    )")
        return out.toString()
    }

    private fun shadowLiteral(layer: CssValues.ShadowLayer): String =
        "QeetrixShadowLayer(inset = ${layer.inset}, offsetX = ${dp(layer.x)}, offsetY = ${dp(layer.y)}, blur = ${dp(layer.blur)}, " +
            "spread = ${dp(layer.spread)}, color = ${colorLiteral(layer.color)})"

    // Typography

    private fun typography(): String {
        val tokens = model.tokensUnder("typography")
        val roles = tokens.map { it.path[1] }.distinct()
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import com.qeetgroup.qeetrix.R")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixFontAxisSpec")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixFontFaceSpec")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixTextRoleSpec")
        out.appendLine()
        out.appendLine("/** The bundled font files, described from the files themselves. */")
        out.appendLine("internal object QeetrixFontTokens {")
        for ((index, font) in fonts.withIndex()) {
            if (index > 0) out.appendLine()
            out.appendLine(
                "    /** `${font.family}` — \"${font.webFamily}\" on the web; the file is ${font.info.familyName} " +
                    "(${font.info.postScriptName}, ${font.info.version}) from ${font.repository} ${font.tag}. */",
            )
            out.appendLine("    val ${KotlinNames.pascal(listOf(font.family), font.family)}: QeetrixFontFaceSpec =")
            out.appendLine("        QeetrixFontFaceSpec(")
            out.appendLine("            resource = R.font.${font.resourceName},")
            out.appendLine("            webFamily = ${kotlinString(font.webFamily)},")
            out.appendLine("            familyName = ${kotlinString(font.info.familyName)},")
            out.appendLine("            postScriptName = ${kotlinString(font.info.postScriptName)},")
            out.appendLine("            axes =")
            out.appendLine("                listOf(")
            for (axis in font.info.axes) {
                out.appendLine(
                    "                    QeetrixFontAxisSpec(${kotlinString(axis.tag)}, minimum = ${floatLiteral(axis.minimum)}, " +
                        "default = ${floatLiteral(axis.defaultValue)}, maximum = ${floatLiteral(axis.maximum)}),",
                )
            }
            out.appendLine("                ),")
            out.appendLine("        )")
        }
        out.appendLine("}")
        out.appendLine()
        out.appendLine(
            "/** `typography.*` — the text roles. Sizes are the default-size values in sp; line height is a multiple of the size. */",
        )
        out.appendLine("internal object QeetrixTypographyTokens {")
        for ((index, role) in roles.withIndex()) {
            val context = "typography.$role"

            fun field(name: String): TokenValue? {
                val token = tokens.firstOrNull { it.path == listOf("typography", role, name) } ?: return null
                return invariant(token)
            }

            fun required(name: String) = field(name) ?: throw GeneratorError("$context: missing $name.")
            val family = (required("font-family") as TokenValue.FontFamily).name
            val font =
                fonts.firstOrNull { it.webFamily == family }
                    ?: throw GeneratorError("$context: font family \"$family\" is not a pinned font. Add it to Upstream/manifest.json.")
            val size = (required("font-size") as TokenValue.Dimension).dp
            val weight = (required("font-weight") as TokenValue.Number).value
            val lineHeight = (required("line-height") as TokenValue.Number).value
            val letterSpacing = (required("letter-spacing") as TokenValue.Em).em
            val geometry = (field("font-geometry") as TokenValue.Number?)?.value
            if (weight != Math.rint(weight)) throw GeneratorError("$context: font-weight $weight is not a whole number.")
            if (index > 0) out.appendLine()
            out.appendLine(
                "    /** `$context` — ${font.webFamily} ${numberText(size)} / ${numberText(lineHeight)}, weight ${numberText(weight)}" +
                    (geometry?.let { ", geometry ${numberText(it)}" } ?: "") + ". */",
            )
            out.appendLine("    val ${KotlinNames.pascal(listOf(role), context)}: QeetrixTextRoleSpec =")
            out.appendLine("        QeetrixTextRoleSpec(")
            out.appendLine("            face = QeetrixFontTokens.${KotlinNames.pascal(listOf(font.family), font.family)},")
            out.appendLine("            size = ${floatLiteral(size)},")
            out.appendLine("            weight = ${numberText(weight)},")
            out.appendLine("            lineHeight = ${floatLiteral(lineHeight)},")
            out.appendLine("            letterSpacing = ${floatLiteral(letterSpacing)},")
            out.appendLine("            geometry = ${geometry?.let(::floatLiteral) ?: "null"},")
            out.appendLine("        )")
        }
        out.appendLine("}")
        return out.toString()
    }

    // Scales

    private fun scales(): String {
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import androidx.compose.animation.core.CubicBezierEasing")
        out.appendLine("import androidx.compose.animation.core.Easing")
        out.appendLine("import androidx.compose.animation.core.LinearEasing")
        out.appendLine("import androidx.compose.ui.unit.Dp")
        out.appendLine("import androidx.compose.ui.unit.dp")
        for (group in scaleGroups) {
            val tokens = model.tokensUnder(*group.prefix.toTypedArray())
            if (tokens.isEmpty()) {
                throw GeneratorError(
                    "${group.prefix.joinToString(".")}: no tokens — remove the group or check the upstream release.",
                )
            }
            val names = tokens.map { KotlinNames.pascal(it.path.drop(group.prefix.size), it.dotted) to it.dotted }
            KotlinNames.requireUnique(names, group.prefix.joinToString("."))
            out.appendLine()
            out.appendLine("/** ${group.doc} */")
            out.appendLine("internal object ${group.objectName} {")
            for ((token, name) in tokens.zip(names)) {
                val (type, literal) = scaleLiteral(group.type, invariant(token), token.dotted)
                out.appendLine("    /** `${token.dotted}` */")
                out.appendLine("    val ${name.first}: $type = $literal")
            }
            out.appendLine("}")
        }
        return out.toString()
    }

    private fun scaleLiteral(
        type: ScaleType,
        value: TokenValue,
        context: String,
    ): Pair<String, String> =
        when {
            type == ScaleType.DP && value is TokenValue.Dimension -> {
                "Dp" to dp(value.dp)
            }

            type == ScaleType.FLOAT && value is TokenValue.Number -> {
                "Float" to floatLiteral(value.value)
            }

            type == ScaleType.INT && value is TokenValue.Number -> {
                if (value.value != Math.rint(value.value)) throw GeneratorError("$context: ${value.value} is not a whole number.")
                "Int" to numberText(value.value)
            }

            type == ScaleType.MOTION && value is TokenValue.Duration -> {
                if (value.millis !=
                    Math.rint(value.millis)
                ) {
                    throw GeneratorError("$context: ${value.millis}ms is not a whole number of milliseconds.")
                }
                "Int" to numberText(value.millis)
            }

            type == ScaleType.MOTION && value is TokenValue.Easing -> {
                "Easing" to
                    if (value.points == listOf(0.0, 0.0, 1.0, 1.0)) {
                        "LinearEasing"
                    } else {
                        "CubicBezierEasing(${value.points.joinToString(", ") { floatLiteral(it) }})"
                    }
            }

            else -> {
                throw GeneratorError("$context: a ${value::class.simpleName} value does not fit a $type scale.")
            }
        }

    // Provenance

    private fun provenanceFile(): String {
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixFontProvenanceSpec")
        out.appendLine()
        out.appendLine("/** Which upstream artifacts this build was generated from. */")
        out.appendLine("internal object QeetrixProvenanceTokens {")
        out.appendLine("    const val TOKENS_PACKAGE: String = ${kotlinString(provenance.uiPackage)}")
        out.appendLine("    const val TOKENS_VERSION: String = ${kotlinString(provenance.uiVersion)}")
        out.appendLine("    const val TOKENS_GIT_HEAD: String = ${kotlinString(provenance.uiGitHead)}")
        out.appendLine("    const val TOKENS_INTEGRITY: String = ${kotlinString(provenance.uiIntegrity)}")
        out.appendLine("    val THEMES: List<String> = listOf(${model.themes.joinToString(", ") { kotlinString(it) }})")
        out.appendLine("    const val GENERATED_TOKENS: Int = ${model.included.size}")
        out.appendLine("    const val EXCLUDED_TOKENS: Int = ${model.excluded.size}")
        out.appendLine("    const val ICONS_PACKAGE: String = ${kotlinString(provenance.iconsPackage)}")
        out.appendLine("    const val ICONS_VERSION: String = ${kotlinString(provenance.iconsVersion)}")
        out.appendLine("    const val ICONS_REPOSITORY: String = ${kotlinString(provenance.iconsRepository)}")
        out.appendLine("    const val ICONS_COMMIT: String = ${kotlinString(provenance.iconsCommit)}")
        out.appendLine("    val FONTS: List<QeetrixFontProvenanceSpec> =")
        out.appendLine("        listOf(")
        for (font in fonts) {
            out.appendLine(
                "            QeetrixFontProvenanceSpec(family = ${kotlinString(
                    font.family,
                )}, webFamily = ${kotlinString(font.webFamily)}, " +
                    "postScriptName = ${kotlinString(font.info.postScriptName)}, version = ${kotlinString(font.info.version)}, " +
                    "repository = ${kotlinString(
                        font.repository,
                    )}, tag = ${kotlinString(font.tag)}, sha256 = ${kotlinString(font.sha256)}),",
            )
        }
        out.appendLine("        )")
        out.appendLine("}")
        return out.toString()
    }

    // Helpers

    /** The single value of a token that must not vary by theme. */
    private fun invariant(token: ResolvedToken): TokenValue {
        if (!token.isThemeInvariant) throw GeneratorError("${token.dotted}: varies by theme, which only colours and elevations may do.")
        return token.values.getValue(model.themes[0])
    }

    companion object {
        const val PACKAGE = "com.qeetgroup.qeetrix.tokens.generated"
        const val GENERATED_DIR = "qeetrix/src/main/kotlin/com/qeetgroup/qeetrix/tokens/generated"

        fun dp(value: Double): String = if (value < 0) "(${numberText(value)}).dp" else "${numberText(value)}.dp"

        /** An sRGB colour as Compose stores it (8 bits per channel); a P3 colour with its components. */
        fun colorLiteral(color: ColorMath.EncodedColor): String =
            when (color.space) {
                ColorMath.Space.SRGB -> {
                    "Color(0x%08X)".format(color.argb)
                }

                ColorMath.Space.DISPLAY_P3 -> {
                    "Color(red = ${floatLiteral(color.red)}, green = ${floatLiteral(color.green)}, blue = ${floatLiteral(color.blue)}, " +
                        "alpha = ${floatLiteral(color.alpha)}, colorSpace = ColorSpaces.DisplayP3)"
                }
            }

        fun describe(color: ColorMath.EncodedColor): String =
            when {
                color.space == ColorMath.Space.SRGB -> color.hex
                color.gamutMapped -> "Display P3, gamut-mapped (${color.hex} clipped to sRGB)"
                else -> "Display P3 (${color.hex} clipped to sRGB)"
            }
    }
}
