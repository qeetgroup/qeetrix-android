/** A bundled font: the pin that produced it plus what the file says about itself. */
data class FontSpec(
    /** `sans` or `mono`: the family key the typography roles use. */
    val family: String,
    val webFamily: String,
    /** The Android resource name, e.g. `qx_qeet_sans_vf`. */
    val resourceName: String,
    /** The TrueType file in `@qeetrix/tokens` it was taken from (`package/dist/fonts/QeetSans.ttf`). */
    val source: String,
    /** The sha256 of the web's WOFF2 the TTF was made from, per `fonts/native.json`. */
    val woff2Sha256: String,
    val ttfSha256: String,
    val info: com.qeetgroup.qeetrix.gen.fonts.FontInfo,
)

/** Where the generated code came from, written into headers and the provenance object. */
data class Provenance(
    val lock: Lock,
) {
    val tokens get() = lock.tokens
    val react get() = lock.react
    val icons get() = lock.icons
}

/**
 * Writes the resolved token model as Kotlin under `tokens/generated`. Every declaration is `internal`:
 * the public API is the hand-written foundation and theme types, which these files construct.
 *
 * Naming, the same rule for every token (Documentation/MIGRATION_QEETRIX_REACT.md has the full table):
 * colours are `QeetrixColors` properties, camelCase of the path after `color.`
 * (`color.bg.brand.bold` → `bgBrandBold`); shadows are `QeetrixShadow` entries; typography roles are
 * `QeetrixTextRole` entries (`typography.body.md` → `BodyMd`); a token the density modifier changes is a
 * `QeetrixDensity` property, camelCase of its whole path (`size.control.md` → `sizeControlMd`); every
 * other token is a constant, PascalCase of the path after its group (`space.inset.md` → `InsetMd`).
 */
class TokenEmitter(
    private val model: TokenModel,
    private val provenance: Provenance,
    private val fonts: List<FontSpec>,
) {
    private val header =
        """
        |// GENERATED by qeetrix-gen from ${provenance.tokens.packageName} ${provenance.tokens.version} (git ${provenance.tokens.gitHead.take(7)}) — do not edit.
        |// Change the upstream tokens, bump Upstream/manifest.json, run Scripts/sync-tokens, then Scripts/generate-tokens.
        |
        """.trimMargin()

    private val themeNames: Map<String, String> = model.themes.associateWith { KotlinNames.pascal(listOf(it), "theme $it") }

    /** One generated scale object: the tokens under [prefix], typed as [type]. */
    class ScaleGroup(
        val prefix: List<String>,
        val objectName: String,
        val type: ScaleType,
        val doc: String,
    )

    enum class ScaleType { DP, FLOAT, INT, MOTION }

    fun files(): Map<String, String> {
        val claimed = HashSet<String>()

        fun claim(tokens: List<ResolvedToken>) = tokens.forEach { claimed += it.dotted }
        val density = model.included.filter { it.followsDensity }
        val files =
            linkedMapOf(
                "QeetrixColorTokens.kt" to colors().also { claim(model.tokensUnder("color")) },
                "QeetrixShadowTokens.kt" to shadows().also { claim(model.tokensUnder("shadow")) },
                "QeetrixTypographyTokens.kt" to
                    typography().also {
                        claim(model.tokensUnder("typography"))
                        claim(model.tokensUnder("font", "family"))
                    },
                "QeetrixScaleTokens.kt" to
                    scales().also {
                        claim(density)
                        SCALE_GROUPS.forEach { group -> claim(scaleTokens(group)) }
                    },
                "QeetrixProvenanceTokens.kt" to provenanceFile(),
            )
        val unclaimed = model.included.filter { it.dotted !in claimed && it.kind != TokenKind.COMPONENT }
        if (unclaimed.isNotEmpty()) {
            throw GeneratorError("No Kotlin home for ${unclaimed.joinToString { it.dotted }}. Map the group in TokenEmitter.")
        }
        return files.mapKeys { "$GENERATED_DIR/${it.key}" }
    }

    // Colours

    private fun colors(): String {
        val tokens = model.tokensUnder("color")
        val names = tokens.map { colorName(it) to it.dotted }
        KotlinNames.requireUnique(names, "color")
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import androidx.compose.ui.graphics.Color")
        if (tokens.any { token -> token.themes.values.any { (it as TokenValue.Color).color.space == ColorMath.Space.DISPLAY_P3 } }) {
            out.appendLine("import androidx.compose.ui.graphics.colorspace.ColorSpaces")
        }
        out.appendLine("import com.qeetgroup.qeetrix.foundation.color.QeetrixColors")
        for (theme in model.themes) {
            out.appendLine()
            out.appendLine("/** The `$theme` colour scheme: every `color.*` token of ${provenance.tokens.packageName}. */")
            out.appendLine("internal val Qeetrix${themeNames.getValue(theme)}Colors: QeetrixColors =")
            out.appendLine("    QeetrixColors(")
            for ((token, name) in tokens.zip(names)) {
                val color = (token.themes.getValue(theme) as TokenValue.Color).color
                val source = token.sources.getValue(theme)
                val via = source.chain.firstOrNull()?.let { " · {$it}" } ?: ""
                out.appendLine("        // ${token.dotted}$via · ${describe(color)}")
                out.appendLine("        ${name.first} = ${colorLiteral(color)},")
            }
            out.appendLine("    )")
        }
        out.appendLine()
        out.appendLine("/** Every colour token's upstream path and its accessor, in upstream order. */")
        out.appendLine("internal val QeetrixColorTokenPaths: List<Pair<String, (QeetrixColors) -> Color>> =")
        out.appendLine("    listOf(")
        for ((token, name) in tokens.zip(names)) out.appendLine("        ${kotlinString(token.dotted)} to QeetrixColors::${name.first},")
        out.appendLine("    )")
        return out.toString()
    }

    // Shadows

    private fun shadows(): String {
        val tokens = model.tokensUnder("shadow")
        val names = tokens.map { KotlinNames.pascal(it.path.drop(1), it.dotted) to it.dotted }
        KotlinNames.requireUnique(names, "shadow")
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        val p3 =
            tokens.any { token ->
                token.themes.values.any { v -> (v as TokenValue.Shadow).layers.any { it.color.space == ColorMath.Space.DISPLAY_P3 } }
            }
        out.appendLine("import androidx.compose.ui.graphics.Color")
        if (p3) out.appendLine("import androidx.compose.ui.graphics.colorspace.ColorSpaces")
        out.appendLine("import androidx.compose.ui.unit.dp")
        out.appendLine("import com.qeetgroup.qeetrix.foundation.elevation.QeetrixShadow")
        out.appendLine("import com.qeetgroup.qeetrix.foundation.elevation.QeetrixShadowLayer")
        for (theme in model.themes) {
            val themeName = themeNames.getValue(theme)
            out.appendLine()
            out.appendLine("/** The `$theme` colour scheme's shadow layers, in CSS order: the first layer is drawn on top. */")
            out.appendLine(
                "internal fun QeetrixShadow.${themeName.replaceFirstChar(Char::lowercaseChar)}Layers(): List<QeetrixShadowLayer> =",
            )
            out.appendLine("    when (this) {")
            for ((_, name) in tokens.zip(names)) out.appendLine("        QeetrixShadow.${name.first} -> $themeName${name.first}")
            out.appendLine("    }")
        }
        for (theme in model.themes) {
            val themeName = themeNames.getValue(theme)
            for ((token, name) in tokens.zip(names)) {
                val layers = (token.themes.getValue(theme) as TokenValue.Shadow).layers
                out.appendLine()
                out.appendLine("// ${token.dotted} ($theme)")
                if (layers.isEmpty()) {
                    out.appendLine("private val $themeName${name.first}: List<QeetrixShadowLayer> = emptyList()")
                    continue
                }
                out.appendLine("private val $themeName${name.first}: List<QeetrixShadowLayer> =")
                out.appendLine("    listOf(")
                for (layer in layers) out.appendLine("        ${shadowLiteral(layer)},")
                out.appendLine("    )")
            }
        }
        out.appendLine()
        out.appendLine("/** Every shadow token's upstream path, in upstream order. */")
        out.appendLine("internal val QeetrixShadowTokenPaths: List<Pair<String, QeetrixShadow>> =")
        out.appendLine("    listOf(")
        for ((token, name) in tokens.zip(names)) out.appendLine("        ${kotlinString(token.dotted)} to QeetrixShadow.${name.first},")
        out.appendLine("    )")
        return out.toString()
    }

    private fun shadowLiteral(layer: ShadowLayer): String =
        "QeetrixShadowLayer(inset = ${layer.inset}, offsetX = ${dp(layer.x)}, offsetY = ${dp(layer.y)}, blur = ${dp(layer.blur)}, " +
            "spread = ${dp(layer.spread)}, color = ${colorLiteral(layer.color)})"

    // Typography

    private fun faceName(font: FontSpec) = KotlinNames.pascal(listOf(font.family), font.family)

    private fun typography(): String {
        val roles = model.tokensUnder("typography")
        val families = model.tokensUnder("font", "family")
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import com.qeetgroup.qeetrix.R")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixFontAxisSpec")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixFontFaceSpec")
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixTextRoleSpec")
        out.appendLine()
        out.appendLine("/** The bundled font files (the TrueType files ${provenance.tokens.packageName} ships), described from the files themselves. */")
        out.appendLine("internal object QeetrixFontFaceTokens {")
        for ((index, font) in fonts.withIndex()) {
            if (index > 0) out.appendLine()
            out.appendLine(
                "    /** `${font.family}` — \"${font.webFamily}\" on the web; the file is ${font.info.familyName} " +
                    "(${font.info.postScriptName}, ${font.info.version}), `${font.source.removePrefix("package/")}`. */",
            )
            out.appendLine("    val ${faceName(font)}: QeetrixFontFaceSpec =")
            out.appendLine("        QeetrixFontFaceSpec(")
            out.appendLine("            resource = R.font.${font.resourceName},")
            out.appendLine("            webFamily = ${kotlinString(font.webFamily)},")
            out.appendLine("            familyName = ${kotlinString(font.info.familyName)},")
            out.appendLine("            postScriptName = ${kotlinString(font.info.postScriptName)},")
            out.appendLine("            axes =")
            out.appendLine("                listOf(")
            for (axis in font.info.axes) {
                out.appendLine(
                    "                    QeetrixFontAxisSpec(${kotlinString(axis.tag)}, minimum = ${floatLiteral(axis.minimum)}, " +
                        "default = ${floatLiteral(axis.defaultValue)}, maximum = ${floatLiteral(axis.maximum)}),",
                )
            }
            out.appendLine("                ),")
            out.appendLine("        )")
        }
        out.appendLine("}")
        out.appendLine()
        out.appendLine("/** `font.family.*` — each family token's first font, the bundled file that draws it. */")
        out.appendLine("internal object QeetrixFontFamilyTokens {")
        for (token in families) {
            val first = (invariant(token) as TokenValue.FontFamily).names.first()
            val font = fontFor(first, token.dotted)
            out.appendLine("    /** `${token.dotted}` — ${first}. */")
            out.appendLine("    val ${KotlinNames.pascal(token.path.drop(2), token.dotted)}: QeetrixFontFaceSpec = QeetrixFontFaceTokens.${faceName(font)}")
        }
        out.appendLine("}")
        out.appendLine()
        val weights = sortedSetOf<Int>()
        out.appendLine(
            "/** `typography.*` — the text roles. Sizes are the default-size values in sp; line height is a multiple of the size, the Float whose product with the size is the token's length exactly; letter spacing in em. */",
        )
        out.appendLine("internal object QeetrixTypographyTokens {")
        for ((index, token) in roles.withIndex()) {
            val value = invariant(token) as TokenValue.Typography
            val font = fontFor(value.family, token.dotted)
            val geometryPath = value.geometry
            val hasGeometryAxis = font.info.axes.any { it.tag == "GEOM" }
            val geometry =
                if (hasGeometryAxis) {
                    (invariant(model.token(geometryPath.joinToString("."))) as TokenValue.Number).value
                } else {
                    null
                }
            weights += value.weight
            if (index > 0) out.appendLine()
            out.appendLine(
                "    /** `${token.dotted}` — ${font.webFamily} ${numberText(value.sizePx)} / ${numberText(value.lineHeightPx)}, weight ${value.weight}" +
                    (geometry?.let { ", GEOM ${numberText(it)} (`${geometryPath.joinToString(".")}`)" } ?: "") + ". */",
            )
            out.appendLine("    val ${KotlinNames.pascal(token.path.drop(1), token.dotted)}: QeetrixTextRoleSpec =")
            out.appendLine("        QeetrixTextRoleSpec(")
            out.appendLine("            face = QeetrixFontFaceTokens.${faceName(font)},")
            out.appendLine("            size = ${floatLiteral(value.sizePx)},")
            out.appendLine("            weight = ${value.weight},")
            out.appendLine("            lineHeight = ${exactFloatLiteral(value.lineHeight)},")
            out.appendLine("            letterSpacing = ${floatLiteral(value.letterSpacingEm)},")
            out.appendLine("            geometry = ${geometry?.let(::floatLiteral) ?: "null"},")
            out.appendLine("        )")
        }
        out.appendLine("}")
        // Every role weight, plus the heaviest each font allows, so Android's Bold Text setting (which raises
        // the requested weight) lands on a real heavier instance instead of a synthesised one.
        for (font in fonts) font.info.axes.firstOrNull { it.tag == "wght" }?.let { weights += it.maximum.toInt() }
        out.appendLine()
        out.appendLine("/** The weights a role's font family is built at: every role's weight, and each font's heaviest. */")
        out.appendLine("internal val QeetrixTypographyWeights: List<Int> = listOf(${weights.joinToString(", ")})")
        return out.toString()
    }

    private fun fontFor(
        family: String,
        context: String,
    ): FontSpec =
        fonts.firstOrNull { it.webFamily == family }
            ?: throw GeneratorError("$context: font family \"$family\" is not a pinned font. Add it to Upstream/manifest.json.")

    // Scales

    private fun scaleTokens(group: ScaleGroup): List<ResolvedToken> = model.tokensUnder(*group.prefix.toTypedArray()).filter { !it.followsDensity }

    private fun scales(): String {
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import androidx.compose.animation.core.CubicBezierEasing")
        out.appendLine("import androidx.compose.animation.core.Easing")
        out.appendLine("import androidx.compose.animation.core.LinearEasing")
        out.appendLine("import androidx.compose.ui.unit.Dp")
        out.appendLine("import androidx.compose.ui.unit.dp")
        out.appendLine("import com.qeetgroup.qeetrix.foundation.sizing.QeetrixDensity")
        for (group in SCALE_GROUPS) {
            val tokens = scaleTokens(group)
            if (tokens.isEmpty()) {
                throw GeneratorError("${group.prefix.joinToString(".")}: no tokens — remove the group or check the upstream release.")
            }
            val names = tokens.map { KotlinNames.pascal(it.path.drop(group.prefix.size), it.dotted) to it.dotted }
            KotlinNames.requireUnique(names, group.prefix.joinToString("."))
            out.appendLine()
            out.appendLine("/** ${group.doc} */")
            out.appendLine("internal object ${group.objectName}Tokens {")
            for ((token, name) in tokens.zip(names)) {
                val (type, literal) = scaleLiteral(group.type, invariant(token), token.dotted)
                out.appendLine("    /** `${token.dotted}` */")
                out.appendLine("    val ${name.first}: $type = $literal")
            }
            out.appendLine("}")
        }
        // Density
        val density = model.included.filter { it.followsDensity }
        val densityNames = model.densities.associateWith { KotlinNames.pascal(listOf(it), "density $it") }
        out.appendLine()
        out.appendLine("/** The tokens the density modifier changes, per density (in the default colour scheme), in dp. */")
        out.appendLine("internal object QeetrixDensityTokens {")
        for ((index, token) in density.withIndex()) {
            if (token.kind != TokenKind.DIMENSION) throw GeneratorError("${token.dotted}: only lengths may follow density.")
            if (index > 0) out.appendLine()
            val name = KotlinNames.camel(token.path, token.dotted)
            out.appendLine(
                "    /** `${token.dotted}` — " +
                    model.densities.joinToString(", ") { "$it ${numberText((token.densities!!.getValue(it) as TokenValue.Dimension).px)}" } + ". */",
            )
            out.appendLine("    fun $name(density: QeetrixDensity): Dp =")
            out.appendLine("        when (density) {")
            for (d in model.densities) {
                out.appendLine("            QeetrixDensity.${densityNames.getValue(d)} -> ${dp((token.densities!!.getValue(d) as TokenValue.Dimension).px)}")
            }
            out.appendLine("        }")
        }
        out.appendLine("}")
        out.appendLine()
        out.appendLine("/** The density contexts, the resolver's default first. */")
        out.appendLine(
            "internal val QeetrixDensityContexts: List<Pair<String, QeetrixDensity>> = listOf(" +
                (listOf(model.defaultDensity) + model.densities.filter { it != model.defaultDensity })
                    .joinToString(", ") { "${kotlinString(it)} to QeetrixDensity.${densityNames.getValue(it)}" } + ")",
        )
        return out.toString()
    }

    private fun scaleLiteral(
        type: ScaleType,
        value: TokenValue,
        context: String,
    ): Pair<String, String> =
        when {
            type == ScaleType.DP && value is TokenValue.Dimension -> {
                "Dp" to dp(value.px)
            }

            type == ScaleType.FLOAT && value is TokenValue.Number -> {
                "Float" to floatLiteral(value.value)
            }

            type == ScaleType.INT && value is TokenValue.Number -> {
                if (value.value != Math.rint(value.value)) throw GeneratorError("$context: ${value.value} is not a whole number.")
                "Int" to numberText(value.value)
            }

            type == ScaleType.MOTION && value is TokenValue.Duration -> {
                if (value.millis != Math.rint(value.millis)) {
                    throw GeneratorError("$context: ${value.millis}ms is not a whole number of milliseconds.")
                }
                "Int" to numberText(value.millis)
            }

            type == ScaleType.MOTION && value is TokenValue.Easing -> {
                "Easing" to
                    if (value.points == listOf(0.0, 0.0, 1.0, 1.0)) {
                        "LinearEasing"
                    } else {
                        "CubicBezierEasing(${value.points.joinToString(", ") { floatLiteral(it) }})"
                    }
            }

            type == ScaleType.MOTION && value is TokenValue.Number -> {
                "Float" to floatLiteral(value.value)
            }

            else -> {
                throw GeneratorError("$context: a ${value::class.simpleName} value does not fit a $type scale.")
            }
        }

    // Provenance

    private fun provenanceFile(): String {
        val out = StringBuilder(header)
        out.appendLine("package $PACKAGE")
        out.appendLine()
        out.appendLine("import com.qeetgroup.qeetrix.internal.QeetrixFontProvenanceSpec")
        out.appendLine()
        out.appendLine("/** Which upstream artifacts this build was generated from. */")
        out.appendLine("internal object QeetrixProvenanceTokens {")
        for ((prefix, pkg) in listOf("TOKENS" to provenance.tokens, "REACT" to provenance.react, "ICONS" to provenance.icons)) {
            out.appendLine("    const val ${prefix}_PACKAGE: String = ${kotlinString(pkg.packageName)}")
            out.appendLine("    const val ${prefix}_VERSION: String = ${kotlinString(pkg.version)}")
            out.appendLine("    const val ${prefix}_GIT_HEAD: String = ${kotlinString(pkg.gitHead)}")
            out.appendLine("    const val ${prefix}_INTEGRITY: String = ${kotlinString(pkg.integrity)}")
        }
        out.appendLine("    val THEMES: List<String> = listOf(${model.themes.joinToString(", ") { kotlinString(it) }})")
        out.appendLine("    val DENSITIES: List<String> = listOf(${model.densities.joinToString(", ") { kotlinString(it) }})")
        out.appendLine("    const val GENERATED_TOKENS: Int = ${model.included.size}")
        out.appendLine("    const val EXCLUDED_TOKENS: Int = ${model.excluded.size}")
        out.appendLine("    const val FONT_TOOLS: String = ${kotlinString(provenance.lock.fontTools)}")
        out.appendLine("    val FONTS: List<QeetrixFontProvenanceSpec> =")
        out.appendLine("        listOf(")
        for (font in fonts) {
            out.appendLine("            QeetrixFontProvenanceSpec(")
            out.appendLine("                family = ${kotlinString(font.family)},")
            out.appendLine("                webFamily = ${kotlinString(font.webFamily)},")
            out.appendLine("                postScriptName = ${kotlinString(font.info.postScriptName)},")
            out.appendLine("                version = ${kotlinString(font.info.version)},")
            out.appendLine("                source = ${kotlinString(font.source.removePrefix("package/"))},")
            out.appendLine("                woff2Sha256 = ${kotlinString(font.woff2Sha256)},")
            out.appendLine("                sha256 = ${kotlinString(font.ttfSha256)},")
            out.appendLine("            ),")
        }
        out.appendLine("        )")
        out.appendLine("}")
        return out.toString()
    }

    // Helpers

    /** The single value of a token that must not vary by theme. */
    private fun invariant(token: ResolvedToken): TokenValue {
        if (!token.isThemeInvariant) throw GeneratorError("${token.dotted}: varies by colour scheme, which only colours and shadows may do.")
        return token.themes.getValue(model.themes[0])
    }

    companion object {
        const val PACKAGE = "com.qeetgroup.qeetrix.tokens.generated"
        const val GENERATED_DIR = "qeetrix/src/main/kotlin/com/qeetgroup/qeetrix/tokens/generated"

        /**
         * The scale objects: the internal generated object, and the public one the foundation builds from it
         * with the same constant names. A token the density modifier changes goes to `QeetrixDensityTokens`
         * instead.
         */
        val SCALE_GROUPS =
            listOf(
                ScaleGroup(listOf("space"), "QeetrixSpace", ScaleType.DP, "`space.*` — insets, gaps and layout spacing, in dp."),
                ScaleGroup(listOf("size"), "QeetrixSize", ScaleType.DP, "`size.*` — icon boxes and the minimum target, in dp."),
                ScaleGroup(listOf("radius"), "QeetrixRadius", ScaleType.DP, "`radius.*` — corner radii, in dp."),
                ScaleGroup(listOf("border"), "QeetrixBorder", ScaleType.DP, "`border.*` — border and rule widths, in dp."),
                ScaleGroup(listOf("focus"), "QeetrixFocus", ScaleType.DP, "`focus.*` — the focus frame, in dp."),
                ScaleGroup(listOf("icon", "stroke"), "QeetrixIconStroke", ScaleType.FLOAT, "`icon.stroke.*` — icon strokes, in 24-unit grid units."),
                ScaleGroup(listOf("opacity"), "QeetrixOpacity", ScaleType.FLOAT, "`opacity.*` — 0–1."),
                ScaleGroup(
                    listOf("motion"),
                    "QeetrixMotion",
                    ScaleType.MOTION,
                    "`motion.*` — durations in milliseconds, easing curves and spring parameters.",
                ),
                ScaleGroup(listOf("breakpoint"), "QeetrixBreakpoint", ScaleType.DP, "`breakpoint.*` — window widths, in dp."),
                ScaleGroup(
                    listOf("font", "geometry"),
                    "QeetrixFontGeometry",
                    ScaleType.FLOAT,
                    "`font.geometry.*` — Qeet Sans's letter styles (the `GEOM` axis).",
                ),
            )

        /** The public Kotlin a token is read through, for the coverage report and the migration table. */
        fun publicAccessor(
            model: TokenModel,
            token: ResolvedToken,
        ): String {
            val path = token.path
            return when {
                path.first() == "color" -> "QeetrixTheme.colors.${colorName(token)}"
                path.first() == "shadow" -> "QeetrixShadow.${KotlinNames.pascal(path.drop(1), token.dotted)}"
                path.first() == "typography" -> "QeetrixTextRole.${KotlinNames.pascal(path.drop(1), token.dotted)} · QeetrixTheme.typography.${KotlinNames.camel(path.drop(1), token.dotted)}"
                path.take(2) == listOf("font", "family") -> "internal: the font of the typography roles that use it"
                token.followsDensity -> "QeetrixTheme.density.${KotlinNames.camel(path, token.dotted)} (QeetrixDensity)"
                token.kind == TokenKind.COMPONENT -> "internal ${ComponentTokenEmitter.objectName(path[1])}.${KotlinNames.pascal(path.drop(2), token.dotted)}"
                path.take(2) == listOf("motion", "spring") -> "QeetrixMotion.${KotlinNames.pascal(path.subList(1, 3), token.dotted)}.${KotlinNames.camel(path.drop(3), token.dotted)}"
                else -> {
                    val group = SCALE_GROUPS.firstOrNull { path.take(it.prefix.size) == it.prefix } ?: throw GeneratorError("${token.dotted}: no public home.")
                    "${group.objectName}.${KotlinNames.pascal(path.drop(group.prefix.size), token.dotted)}"
                }
            }.also { if (model.included.none { it.dotted == token.dotted }) throw GeneratorError("${token.dotted} is not generated.") }
        }

        /** A colour token's `QeetrixColors` property: camelCase of the path after `color.`. */
        fun colorName(token: ResolvedToken): String = KotlinNames.camel(token.path.drop(1), token.dotted)

        fun dp(value: Double): String = if (value < 0) "(${numberText(value)}).dp" else "${numberText(value)}.dp"

        /** An sRGB colour as Compose stores it (8 bits per channel); a P3 colour with its components. */
        fun colorLiteral(color: ColorMath.EncodedColor): String =
            when (color.space) {
                ColorMath.Space.SRGB -> {
                    "Color(0x%08X)".format(color.argb)
                }

                ColorMath.Space.DISPLAY_P3 -> {
                    "Color(red = ${floatLiteral(color.red)}, green = ${floatLiteral(color.green)}, blue = ${floatLiteral(color.blue)}, " +
                        "alpha = ${floatLiteral(color.alpha)}, colorSpace = ColorSpaces.DisplayP3)"
                }
            }

        fun describe(color: ColorMath.EncodedColor): String =
            when {
                color.space == ColorMath.Space.SRGB -> color.hex
                color.gamutMapped -> "Display P3, gamut-mapped (${color.hex} clipped to sRGB)"
                else -> "Display P3 (${color.hex} clipped to sRGB)"
            }
    }
