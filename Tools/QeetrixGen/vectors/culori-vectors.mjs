// Writes src/test/resources/culori-vectors.json: for every colour input in
// Documentation/Foundations/token-values.json, the sRGB hex culori produces with the exact colour-mix
// and clamping logic of qeetrix-ui's contrast gate (src/__tests__/token-governance.test.ts, `toColor`
// + culori `formatHex8`). It is an independent oracle for the generator's colour conversion: the web's
// own converter, not this repository's.
//
// Development only — nothing in the build runs it. Usage, with culori 4.0.2 installed anywhere Node
// can resolve it (qeetrix-ui's node_modules has it):
//   NODE_PATH=../qeetrix-ui/node_modules node Tools/QeetrixGen/vectors/culori-vectors.mjs <repo-root>
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(join(process.env.NODE_PATH ?? ".", "noop.js"));
const culori = require("culori");
const { converter, formatHex8, parse } = culori;
const oklab = converter("oklab");
const version = require("culori/package.json").version;

const splitTopLevel = (s) => {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const ch of s) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else current += ch;
  }
  parts.push(current.trim());
  return parts;
};

// Verbatim from qeetrix-ui src/__tests__/token-governance.test.ts.
function toColor(expression) {
  const expr = expression.trim();
  if (expr === "transparent") return { mode: "rgb", r: 0, g: 0, b: 0, alpha: 0 };
  const mix = /^color-mix\(\s*in oklab\s*,([\s\S]*)\)$/.exec(expr);
  if (!mix) {
    const parsed = parse(expr);
    if (!parsed) throw new Error(`not a colour: ${expr}`);
    return parsed;
  }
  const [a, b] = splitTopLevel(mix[1]).map((part) => {
    const m = /^(.*?)\s+(\d+(?:\.\d+)?)%$/.exec(part);
    return m ? { c: toColor(m[1]), p: Number(m[2]) / 100 } : { c: toColor(part), p: null };
  });
  const pa = a.p ?? (b.p === null ? 0.5 : 1 - b.p);
  const pb = 1 - pa;
  const la = oklab(a.c);
  const lb = oklab(b.c);
  const aa = la.alpha ?? 1;
  const ab = lb.alpha ?? 1;
  const alpha = aa * pa + ab * pb;
  const channel = (k) => (alpha === 0 ? 0 : (la[k] * aa * pa + lb[k] * ab * pb) / alpha);
  return { mode: "oklab", l: channel("l"), a: channel("a"), b: channel("b"), alpha };
}

const root = process.argv[2] ?? ".";
const values = JSON.parse(readFileSync(join(root, "Documentation/Foundations/token-values.json"), "utf8"));
const vectors = {};
for (const [path, token] of Object.entries(values.tokens)) {
  if (token.kind !== "color") continue;
  for (const [theme, { input }] of Object.entries(token.themes)) {
    vectors[`${path}@${theme}`] = { input, hex: formatHex8(toColor(input)).toUpperCase() };
  }
}
const out = {
  $comment: `GENERATED by Tools/QeetrixGen/vectors/culori-vectors.mjs with culori ${version} — the converter qeetrix-ui's contrast gate uses — from ${values.source.package}@${values.source.version}. Hex is #RRGGBBAA, channels clamped per culori.`,
  culori: version,
  vectors,
};
writeFileSync(join(root, "Tools/QeetrixGen/src/test/resources/culori-vectors.json"), `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${Object.keys(vectors).length} vectors`);
